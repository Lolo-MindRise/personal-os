import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { MIGRATIONS_DIR } from './config.js';
import { stripSqlComments, unsafeReasons } from './migrationSafety.js';

/**
 * Reviewed exceptions: migration file name → one-line reason. Empty today, and it should stay
 * that way. Only Manuel adds an entry, after reviewing the migration by hand (CLAUDE.md: a
 * migration must not DROP TABLE or rebuild an existing table).
 */
const ALLOWED: Record<string, string> = {};

const files = readdirSync(MIGRATIONS_DIR)
  .filter((name) => name.endsWith('.sql'))
  .sort();
const read = (name: string) => readFileSync(join(MIGRATIONS_DIR, name), 'utf8');

describe('migrations in drizzle/', () => {
  it('finds the migrations', () => {
    expect(files.length).toBeGreaterThanOrEqual(6);
  });

  for (const name of files) {
    it(`${name} drops no table and rebuilds none`, () => {
      const reasons = unsafeReasons(read(name));
      if (name in ALLOWED) {
        // An exception only makes sense for a file that really needs it.
        expect(reasons, `${name} is allowed but is safe: remove it from ALLOWED`).not.toEqual([]);
      } else {
        expect(
          reasons,
          `${name} ${reasons.join(' and ')}. Write an additive migration by hand ` +
            `(ALTER TABLE ... ADD COLUMN, CREATE TABLE, CREATE INDEX) and test that existing rows survive; ` +
            `if an exception is truly needed, Manuel adds it to ALLOWED with a reason.`,
        ).toEqual([]);
      }
    });
  }

  it('the allow list only names existing migrations, each with a reason', () => {
    for (const [name, reason] of Object.entries(ALLOWED)) {
      expect(existsSync(join(MIGRATIONS_DIR, name)), `${name} does not exist`).toBe(true);
      expect(reason.trim(), `${name} needs a reason`).not.toBe('');
    }
  });
});

describe('unsafeReasons', () => {
  // What drizzle-kit generates to add a CHECK or change a column: the pattern to catch.
  const rebuild = [
    'PRAGMA foreign_keys=OFF;--> statement-breakpoint',
    'CREATE TABLE `__new_recurring_items` (`id` integer PRIMARY KEY NOT NULL);--> statement-breakpoint',
    'INSERT INTO `__new_recurring_items`("id") SELECT "id" FROM `recurring_items`;--> statement-breakpoint',
    'DROP TABLE `recurring_items`;--> statement-breakpoint',
    'ALTER TABLE `__new_recurring_items` RENAME TO `recurring_items`;--> statement-breakpoint',
    'PRAGMA foreign_keys=ON;',
  ].join('\n');

  it('flags a table rebuild as generated by drizzle-kit', () => {
    expect(unsafeReasons(rebuild)).toEqual([
      'contains DROP TABLE',
      'rebuilds a table (a __new_ table)',
    ]);
  });

  it('flags DROP TABLE in any case and spacing', () => {
    for (const sql of [
      'DROP TABLE x;',
      'drop table x;',
      'Drop\n\tTable `x`;',
      'DROP TABLE IF EXISTS x;',
    ]) {
      expect(unsafeReasons(sql), sql).toContain('contains DROP TABLE');
    }
  });

  it('flags creating a __new_ table on its own', () => {
    expect(unsafeReasons('CREATE TABLE "__new_goals" (id integer);')).toEqual([
      'rebuilds a table (a __new_ table)',
    ]);
  });

  it('accepts additive migrations', () => {
    const additive = [
      'CREATE TABLE `category_rules` (`id` integer PRIMARY KEY NOT NULL);',
      '--> statement-breakpoint',
      'ALTER TABLE `recurring_items` ADD `debt_id` integer REFERENCES `debts`(`id`);',
      'CREATE UNIQUE INDEX `movements_x` ON `movements` (`recurring_item_id`);',
      'DROP INDEX `old_index`;',
    ].join('\n');
    expect(unsafeReasons(additive)).toEqual([]);
  });

  it('ignores comments, so a migration may explain why it avoids a rebuild', () => {
    const sql = [
      '-- drizzle-kit would DROP TABLE recurring_items and create __new_recurring_items.',
      '/* DROP TABLE again, in a block comment',
      '   spanning lines */',
      'ALTER TABLE `recurring_items` ADD `debt_id` integer;',
    ].join('\n');
    expect(stripSqlComments(sql)).not.toMatch(/drop table|__new_/i);
    expect(unsafeReasons(sql)).toEqual([]);
  });

  it('still flags code that follows a comment on the same line', () => {
    expect(unsafeReasons('/* note */ DROP TABLE x;')).toContain('contains DROP TABLE');
  });
});
